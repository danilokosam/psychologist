-- Integrity --------------------------------------------------------------

-- Emails are compared for equality against the verified token's email claim,
-- so they must be stored in one canonical form.
ALTER TABLE "invitations" ADD CONSTRAINT "invitations_email_normalized"
  CHECK (email = lower(btrim(email)) AND email <> '');

-- Ownership transfer is not an invitation.
ALTER TABLE "invitations" ADD CONSTRAINT "invitations_role_not_owner"
  CHECK (role <> 'owner');

-- The lifecycle columns must agree with the status, so a row can never claim
-- to be accepted without saying by whom and when (or be both).
ALTER TABLE "invitations" ADD CONSTRAINT "invitations_state_consistent" CHECK (
     (status = 'pending'  AND accepted_by IS NULL     AND accepted_at IS NULL     AND revoked_at IS NULL)
  OR (status = 'accepted' AND accepted_by IS NOT NULL AND accepted_at IS NOT NULL AND revoked_at IS NULL)
  OR (status = 'revoked'  AND accepted_by IS NULL     AND accepted_at IS NULL     AND revoked_at IS NOT NULL)
);

ALTER TABLE "invitations" ADD CONSTRAINT "invitations_expiry_after_creation"
  CHECK (expires_at > created_at);

-- At most one live invitation per address per organization. Partial, so
-- accepted/revoked history doesn't block inviting the same person again.
CREATE UNIQUE INDEX "invitations_one_pending_per_email"
  ON "invitations" ("organization_id", "email")
  WHERE status = 'pending';

-- Grants -----------------------------------------------------------------
-- Default privileges gave app_runtime full SELECT/INSERT/UPDATE/DELETE on this
-- new table. Narrow it: an existing invitation's email, role, organization and
-- token hash can never be changed through the application, only its
-- lifecycle columns; and nothing is ever deleted (revoking is a status
-- change, so who-granted-access-to-whom stays auditable).
REVOKE UPDATE, DELETE ON "invitations" FROM app_runtime;
GRANT UPDATE ("status", "accepted_by", "accepted_at", "revoked_at") ON "invitations" TO app_runtime;

-- Row Level Security -----------------------------------------------------
-- Every identity value is read through the app_private helpers, and the owner
-- check is re-derived from `memberships` -- never from a role passed in by
-- the application (ADR-0003, ADR-0012).

ALTER TABLE "invitations" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "invitations" FORCE ROW LEVEL SECURITY;

-- Owners of the declared organization see all its invitations; an invitee
-- sees only pending invitations addressed to their own verified email, plus
-- the one they accepted themselves. That last branch is not optional:
-- Postgres requires the NEW row of an `UPDATE ... RETURNING` (what Prisma
-- issues) to pass the SELECT policy too, so without it accepting would fail
-- the moment the status left 'pending'.
CREATE POLICY "invitations_select" ON "invitations"
  FOR SELECT
  USING (
    (
      organization_id = (select app_private.current_org_id())
      AND EXISTS (
        SELECT 1 FROM memberships m
        WHERE m.organization_id = invitations.organization_id
          AND m.user_id = (select app_private.current_user_id())
          AND m.role = 'owner' AND m.status = 'active'
      )
    )
    OR (
      status = 'pending'
      AND email = (select app_private.current_user_email())
    )
    OR accepted_by = (select app_private.current_user_id())
  );

-- Only an active owner, only into the declared organization, only as
-- themselves, and only as a fresh pending invitation.
CREATE POLICY "invitations_insert" ON "invitations"
  FOR INSERT
  WITH CHECK (
    organization_id = (select app_private.current_org_id())
    AND invited_by = (select app_private.current_user_id())
    AND status = 'pending'
    AND EXISTS (
      SELECT 1 FROM memberships m
      WHERE m.organization_id = invitations.organization_id
        AND m.user_id = (select app_private.current_user_id())
        AND m.role = 'owner' AND m.status = 'active'
    )
  );

-- Two legitimate transitions, merged into one policy (multiple permissive
-- policies per action are a real per-query cost -- see SECURITY.md):
--   * an owner revokes a pending invitation of the declared organization;
--   * the invitee accepts a pending, unexpired invitation to their own email,
--     recording themselves as the acceptor.
CREATE POLICY "invitations_update" ON "invitations"
  FOR UPDATE
  USING (
    status = 'pending'
    AND (
      (
        organization_id = (select app_private.current_org_id())
        AND EXISTS (
          SELECT 1 FROM memberships m
          WHERE m.organization_id = invitations.organization_id
            AND m.user_id = (select app_private.current_user_id())
            AND m.role = 'owner' AND m.status = 'active'
        )
      )
      OR (
        email = (select app_private.current_user_email())
        AND expires_at > now()
      )
    )
  )
  WITH CHECK (
    (
      status = 'revoked'
      AND organization_id = (select app_private.current_org_id())
      AND EXISTS (
        SELECT 1 FROM memberships m
        WHERE m.organization_id = invitations.organization_id
          AND m.user_id = (select app_private.current_user_id())
          AND m.role = 'owner' AND m.status = 'active'
      )
    )
    OR (
      status = 'accepted'
      AND accepted_by = (select app_private.current_user_id())
      AND email = (select app_private.current_user_email())
    )
  );
-- No DELETE policy (and no DELETE grant): invitations are never deleted
-- through the application.

-- memberships: second legitimate way in ------------------------------------
-- Until now a caller could only add themselves to an organization they had
-- just created (bootstrap). Accepting an invitation is the second case: add
-- yourself, as an active member, with exactly the invited role, only while a
-- pending unexpired invitation exists for YOUR verified email. Merged into
-- one policy for the same reason as above. has_pending_invitation is SECURITY
-- DEFINER: invitations' own policies read memberships, so reading invitations
-- from a memberships policy directly would be rejected as recursive (42P17).
DROP POLICY IF EXISTS "memberships_self_insert" ON "memberships";
CREATE POLICY "memberships_insert" ON "memberships"
  FOR INSERT
  WITH CHECK (
    user_id = (select app_private.current_user_id())
    AND (
      app_private.is_organization_creator(organization_id)
      OR (
        status = 'active'
        AND app_private.has_pending_invitation(organization_id, role::text)
      )
    )
  );
