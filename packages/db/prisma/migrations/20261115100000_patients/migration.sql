-- Integrity --------------------------------------------------------------
-- The API's Zod schemas enforce the same rules; these hold even for a write
-- that bypasses the application. Length caps also bound what a buggy or
-- malicious client can store.

ALTER TABLE "patients" ADD CONSTRAINT "patients_full_name_valid"
  CHECK (full_name = btrim(full_name) AND full_name <> '' AND char_length(full_name) <= 200);

-- Search and future de-duplication compare emails, so one canonical form.
ALTER TABLE "patients" ADD CONSTRAINT "patients_email_normalized"
  CHECK (email IS NULL OR (email = lower(btrim(email)) AND email <> '' AND char_length(email) <= 320));

ALTER TABLE "patients" ADD CONSTRAINT "patients_phone_valid"
  CHECK (phone IS NULL OR (phone = btrim(phone) AND phone <> '' AND char_length(phone) <= 30));

ALTER TABLE "patients" ADD CONSTRAINT "patients_emergency_contact_valid" CHECK (
      (emergency_contact_name IS NULL OR (emergency_contact_name = btrim(emergency_contact_name)
        AND emergency_contact_name <> '' AND char_length(emergency_contact_name) <= 200))
  AND (emergency_contact_phone IS NULL OR (emergency_contact_phone = btrim(emergency_contact_phone)
        AND emergency_contact_phone <> '' AND char_length(emergency_contact_phone) <= 30))
);

-- "Not in the future" is checked by the API only: current_date is not
-- immutable, and a CHECK that depends on the clock is not re-evaluated.
ALTER TABLE "patients" ADD CONSTRAINT "patients_date_of_birth_plausible"
  CHECK (date_of_birth IS NULL OR date_of_birth >= DATE '1900-01-01');

-- A row can never claim to be archived without saying when (or vice versa).
ALTER TABLE "patients" ADD CONSTRAINT "patients_archived_consistent"
  CHECK ((status = 'archived') = (archived_at IS NOT NULL));

-- Grants -----------------------------------------------------------------
-- Default privileges gave app_runtime full SELECT/INSERT/UPDATE/DELETE.
-- Narrow it (ADR-0014): no DELETE at all -- patients are archived, never
-- deleted, through the application -- and UPDATE only on the columns a
-- patient edit or an archive/restore legitimately changes. Never the id,
-- organization, creator or creation time.
REVOKE UPDATE, DELETE ON "patients" FROM app_runtime;
GRANT UPDATE (
  "full_name", "date_of_birth", "email", "phone",
  "emergency_contact_name", "emergency_contact_phone",
  "status", "archived_at", "updated_at"
) ON "patients" TO app_runtime;

-- Row Level Security -----------------------------------------------------
-- Both conditions on every policy (ADR-0012): the declared organization
-- (stops the application reading an organization it did not ask for) AND a
-- membership verified by the database (holds even if the application layer
-- has a bug). Identity is read only through the app_private helpers.

ALTER TABLE "patients" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "patients" FORCE ROW LEVEL SECURITY;

-- Every role reads patients (SECURITY.md matrix), archived ones included:
-- an archived patient's history must stay viewable.
CREATE POLICY "patients_select" ON "patients"
  FOR SELECT
  USING (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
  );

-- Every role creates patients, only as themselves, and never pre-archived
-- (archiving is an owner decision -- see below).
CREATE POLICY "patients_insert" ON "patients"
  FOR INSERT
  WITH CHECK (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND created_by = (select app_private.current_user_id())
    AND status <> 'archived'
  );

-- Every role edits patients, but archived ones are owner-only on BOTH
-- sides of the update:
--   USING      -- only an owner can touch a row that is archived now
--                 (so only an owner restores, or edits an archived row);
--   WITH CHECK -- only an owner can leave a row archived (so only an owner
--                 archives).
-- The owner check is re-derived from memberships by has_active_role, never
-- taken from the application (ADR-0003). This is what makes "admin_staff
-- cannot archive" true even with the app-layer check removed.
CREATE POLICY "patients_update" ON "patients"
  FOR UPDATE
  USING (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND (status <> 'archived' OR app_private.has_active_role(organization_id, ARRAY['owner']))
  )
  WITH CHECK (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND (status <> 'archived' OR app_private.has_active_role(organization_id, ARRAY['owner']))
  );
-- No DELETE policy (and no DELETE grant): see ADR-0014.
