-- Row Level Security -----------------------------------------------------
-- Every policy: the declared organization AND a membership verified by the
-- database (ADR-0012). Every role may create, read, update and cancel
-- (SECURITY.md matrix) -- the role-aware rules here are about the
-- *professional* booked and the *patient*, not the caller.

ALTER TABLE "appointments" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "appointments" FORCE ROW LEVEL SECURITY;

CREATE POLICY "appointments_select" ON "appointments"
  FOR SELECT
  USING (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
  );

-- Only as yourself; never pre-cancelled; the professional must be an active
-- owner/psychologist (admin_staff do not see patients clinically); and the
-- patient must not be archived (archived records are frozen, ADR-0014).
-- The patients sub-select runs under the caller's own patients policies.
CREATE POLICY "appointments_insert" ON "appointments"
  FOR INSERT
  WITH CHECK (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND created_by = (select app_private.current_user_id())
    AND status <> 'cancelled'
    AND app_private.is_active_clinician(organization_id, professional_id)
    AND EXISTS (
      SELECT 1 FROM patients p
      WHERE p.id = appointments.patient_id
        AND p.organization_id = appointments.organization_id
        AND p.status <> 'archived'
    )
  );

-- USING: a cancelled appointment is final -- nobody edits or "un-cancels" it
-- (book a new one instead).
-- WITH CHECK: the professional must still be a valid clinician -- except
-- when the update is the cancellation itself, which must always be possible
-- (e.g. for an appointment whose professional has since been suspended).
CREATE POLICY "appointments_update" ON "appointments"
  FOR UPDATE
  USING (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND status <> 'cancelled'
  )
  WITH CHECK (
    organization_id = (select app_private.current_org_id())
    AND app_private.is_active_member(organization_id)
    AND (status = 'cancelled' OR app_private.is_active_clinician(organization_id, professional_id))
  );
-- No DELETE policy (and no DELETE grant).
