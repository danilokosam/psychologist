-- Integrity --------------------------------------------------------------

-- A real time range, and a sane one: 12 hours bounds a typo (an end date a
-- year out) without constraining any real session format.
ALTER TABLE "appointments" ADD CONSTRAINT "appointment_time_valid" CHECK (
  scheduled_end > scheduled_start
  AND scheduled_end - scheduled_start <= interval '12 hours'
);

ALTER TABLE "appointments" ADD CONSTRAINT "appointments_cancelled_consistent"
  CHECK ((status = 'cancelled') = (cancelled_at IS NOT NULL));

-- F-007: no double-booking, enforced by the database itself. Half-open
-- ranges '[)' so back-to-back appointments (10:00-11:00, 11:00-12:00) are
-- allowed. `cancelled` is the only status that frees the slot: scheduled,
-- confirmed, completed and no_show all represent time that was taken.
--
-- Scoped per organization (ADR-0015): a professional who belongs to two
-- practices is not checked across them, because the conflict error itself
-- would tell one practice that the other has a booking at that time -- a
-- cross-tenant leak. Each practice's own calendar is airtight.
ALTER TABLE "appointments" ADD CONSTRAINT "no_professional_overlap"
  EXCLUDE USING gist (
    organization_id WITH =,
    professional_id WITH =,
    tstzrange(scheduled_start, scheduled_end, '[)') WITH &&
  ) WHERE (status <> 'cancelled');

ALTER TABLE "appointments" ADD CONSTRAINT "no_patient_overlap"
  EXCLUDE USING gist (
    organization_id WITH =,
    patient_id WITH =,
    tstzrange(scheduled_start, scheduled_end, '[)') WITH &&
  ) WHERE (status <> 'cancelled');

-- Grants -----------------------------------------------------------------
