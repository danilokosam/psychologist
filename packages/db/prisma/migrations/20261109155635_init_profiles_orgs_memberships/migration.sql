-- ===========================================================================
-- Manual additions below (not generated by `prisma migrate diff`):
-- RLS policies and grants for the least-privilege app_runtime role. See
-- docs/SECURITY.md and docs/decisions/0003-defense-in-depth-tenant-isolation.md.
--
-- NOTE: the profiles.id -> auth.users.id foreign key is deliberately NOT
-- here. Supabase actively prevents granting any privilege on the `auth`
-- schema to custom roles (confirmed: a GRANT that reports success doesn't
-- actually persist) -- app_migrator cannot own that constraint. It's added
-- separately, once, via `supabase db query` using the privileged admin
-- connection, which does have rights on `auth.users`. See
-- packages/db/sql/profiles-auth-fk.sql.
-- ===========================================================================

-- Future tables created by app_migrator automatically grant to app_runtime,
-- so later migrations don't need to remember this step.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_runtime;

GRANT SELECT, INSERT, UPDATE, DELETE ON "profiles", "organizations", "memberships" TO app_runtime;

-- ---------------------------------------------------------------------------
-- Row Level Security. Enabled AND forced on every table -- FORCE is what
-- makes RLS apply even to a table's owner (app_migrator), not just to
-- other roles. app_runtime itself is a non-owner, non-superuser role with
-- NOBYPASSRLS (set at role creation), so RLS always applies to it regardless.
-- ---------------------------------------------------------------------------

ALTER TABLE "profiles" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "profiles" FORCE ROW LEVEL SECURITY;

-- A user can always see their own profile.
CREATE POLICY "profiles_self_select" ON "profiles"
  FOR SELECT
  USING (id = current_setting('app.current_user_id', true)::uuid);

-- ...and the profile of anyone who shares an active organization with them
-- (needed to display teammate names -- membership visibility alone, via
-- memberships_org_select below, doesn't include the display name).
CREATE POLICY "profiles_orgmate_select" ON "profiles"
  FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM memberships m1
      JOIN memberships m2 ON m1.organization_id = m2.organization_id
      WHERE m1.user_id = profiles.id
        AND m2.user_id = current_setting('app.current_user_id', true)::uuid
        AND m1.status = 'active' AND m2.status = 'active'
    )
  );

-- A profile can only be created/edited by the user it belongs to (their own
-- row, keyed by their own auth.users id -- never on behalf of someone else).
CREATE POLICY "profiles_self_insert" ON "profiles"
  FOR INSERT
  WITH CHECK (id = current_setting('app.current_user_id', true)::uuid);

CREATE POLICY "profiles_self_update" ON "profiles"
  FOR UPDATE
  USING (id = current_setting('app.current_user_id', true)::uuid)
  WITH CHECK (id = current_setting('app.current_user_id', true)::uuid);

ALTER TABLE "organizations" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "organizations" FORCE ROW LEVEL SECURITY;

-- Visible to any active member -- needed for the org-switcher, which lists
-- every organization a user belongs to before one becomes "active".
CREATE POLICY "organizations_member_select" ON "organizations"
  FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM memberships m
      WHERE m.organization_id = organizations.id
        AND m.user_id = current_setting('app.current_user_id', true)::uuid
        AND m.status = 'active'
    )
  );

-- Creating an organization has no row to scope against yet -- the identity
-- check already happened one layer up (JWT verification before the request
-- ever reaches the database); this policy exists so RLS doesn't block the
-- INSERT outright, not to add further restriction.
CREATE POLICY "organizations_insert" ON "organizations"
  FOR INSERT
  WITH CHECK (true);

-- Only an owner can edit organization settings.
CREATE POLICY "organizations_owner_update" ON "organizations"
  FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM memberships m
      WHERE m.organization_id = organizations.id
        AND m.user_id = current_setting('app.current_user_id', true)::uuid
        AND m.role = 'owner' AND m.status = 'active'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM memberships m
      WHERE m.organization_id = organizations.id
        AND m.user_id = current_setting('app.current_user_id', true)::uuid
        AND m.role = 'owner' AND m.status = 'active'
    )
  );

ALTER TABLE "memberships" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "memberships" FORCE ROW LEVEL SECURITY;

-- A user can always see their own memberships, across every organization --
-- needed to populate the org-switcher before any org is "active" yet.
CREATE POLICY "memberships_self_select" ON "memberships"
  FOR SELECT
  USING (user_id = current_setting('app.current_user_id', true)::uuid);

-- Not role-gated: team roster visibility isn't the sensitive data here (see
-- docs/SECURITY.md); the sensitive table is clinical_notes, added later.
-- Must stay non-circular -- this is exactly what lets clinical tables,
-- added in future migrations, safely query memberships inside their own
-- policies.
CREATE POLICY "memberships_org_select" ON "memberships"
  FOR SELECT
  USING (organization_id = current_setting('app.current_org_id', true)::uuid);
